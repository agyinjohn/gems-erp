export interface StorefrontSettings {
  delivery_fee: number;
  free_delivery_threshold: number;
  store_enabled: boolean;
  announcement?: string;
  min_order_amount?: number;
  tax_rate?: number;
  tax_name?: string;
  custom_domain?: string;
  delivery_estimate?: string;       // e.g. "3 – 5 business days"
  location_suggestions?: string[];  // e.g. ["Accra", "Kumasi"]
  phone_placeholder?: string;       // e.g. "+233 XX XXX XXXX"
  // How the shop looks. Empty means the GEMS navy, which is what every
  // storefront was before a shop could choose.
  brand_color?: string;
  banner_image?: string;
  tagline?: string;
  hero_headline?: string;
  /** Lives on the tenant, not in storefront_settings — see the controller. */
  logo?: string;
}

// ── Shared TypeScript interfaces ────────────────────────────────────────────
/** One question a customer answers: "Size", and the values on offer. */
export interface ProductOption {
  name: string;
  values: { value: string; in_stock: boolean }[];
}

/** One buyable combination — a navy medium — with its own price and count. */
export interface ProductVariant {
  /** Canonical identity, generated by the server. Never built on the client. */
  key: string;
  selections: { name: string; value: string }[];
  price: number;
  available: number;
  sku?: string;
}

export interface StoreProduct {
  id: string;
  name: string;
  /** The product's public address. Absent until the backfill has run. */
  slug?: string;
  price: number;
  // cost_price is deliberately absent: the public catalogue endpoint used to
  // send it — what the shop paid, for every item — and nothing ever showed it.
  compare_price?: number;
  /**
   * The name of the promotion that produced the reduced price, when one did.
   *
   * Set by the server as it applies promotions, so a card can say "Easter Sale"
   * where it would otherwise say "Save 25%". The shop's own words beat a
   * calculated percentage.
   */
  promotion_name?: string;
  /**
   * What the customer must choose before they can order, and which values are
   * still available. Absent or empty for the great majority of products, which
   * come one way.
   */
  options?: ProductOption[];
  /** Every combination that can be bought, with its own price and count. */
  variants?: ProductVariant[];
  description?: string;
  sku?: string;
  images: string[];
  stock_qty: number;
  low_stock_threshold: number;
  category_name?: string;
  branch_id?: string;
  branch_name?: string;
  branch_slug?: string;
  is_active: boolean;
  item_type?: 'product' | 'service' | 'bundle';
  unit_type?: string;
  duration?: number;
  /** All stored since the catalogue was built, and shown for the first time. */
  unit?: string;
  attributes?: Record<string, unknown>;
  /** Resolved against the category server-side: real labels, chosen order. */
  specs?: { label?: string; value?: string }[];
  short_description?: string;
  brand?: string;
  highlights?: string[];
  bundle_items?: { name?: string; quantity?: number }[];
  requires_file?: boolean;
  service_type?: string;
}

