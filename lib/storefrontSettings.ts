/**
 * What the shop front says when the owner has written nothing.
 *
 * It advertises rather than merely stating a fact, because most shops will
 * never open the settings page and this line is what their customers read. It
 * promises only things GEMS actually does: the whole range is browsable, the
 * order takes a moment, and payment goes through Paystack by card or mobile
 * money. Nothing here mentions delivery, which is not true of a shop selling
 * services.
 *
 * Defined once. It was written out separately in the storefront and in the
 * settings preview, which is a drift waiting to happen — the preview is
 * supposed to be the promise that the shop front will look like this.
 */
export const DEFAULT_HERO_MESSAGE =
  'Browse everything we have, order in a few taps, and pay securely by card or mobile money.';

/**
 * Whether a stock figure means anything for this item.
 *
 * The storefront has always asked `stock_qty > 0` of anything that was not a
 * service, and a bundle is neither. A bundle holds no stock of its own — it is
 * available while the things inside it are, and the catalogue says so: stock
 * on the model is documented as ignored for services and bundles alike. So the
 * shop front read every bundle as sold out, refused to put one in a cart, and
 * hid it behind the "in stock only" filter. Nothing had ever been a bundle
 * before now, which is why nobody had seen it.
 */
export function tracksStock(item: { item_type?: string }): boolean {
  return item.item_type !== 'service' && item.item_type !== 'bundle';
}

/** Whether a customer can buy this right now. */
export function isAvailable(item: { item_type?: string; stock_qty?: number }): boolean {
  return !tracksStock(item) || (item.stock_qty ?? 0) > 0;
}

export const DEFAULT_STOREFRONT_SETTINGS: StorefrontSettings = {
  delivery_fee: 30,
  free_delivery_threshold: 500,
  store_enabled: true,
  announcement: '',
  min_order_amount: 0,
  delivery_estimate: '3 – 5 business days',
  location_suggestions: [],
  phone_placeholder: '',
};

export function normalizeStorefrontSettings(raw: Partial<StorefrontSettings> | null | undefined): StorefrontSettings {
  return {
    delivery_fee: Number(raw?.delivery_fee ?? DEFAULT_STOREFRONT_SETTINGS.delivery_fee),
    free_delivery_threshold: Number(raw?.free_delivery_threshold ?? DEFAULT_STOREFRONT_SETTINGS.free_delivery_threshold),
    store_enabled: raw?.store_enabled ?? DEFAULT_STOREFRONT_SETTINGS.store_enabled,
    announcement: raw?.announcement ?? '',
    min_order_amount: Number(raw?.min_order_amount ?? 0),
    tax_rate: Number(raw?.tax_rate ?? 0),
    tax_name: raw?.tax_name ?? '',
    custom_domain: String(raw?.custom_domain ?? '').toLowerCase().trim(),
    delivery_estimate: raw?.delivery_estimate ?? DEFAULT_STOREFRONT_SETTINGS.delivery_estimate,
    location_suggestions: Array.isArray(raw?.location_suggestions) ? raw.location_suggestions : [],
    phone_placeholder: raw?.phone_placeholder ?? '',
    // This function rebuilds the object field by field, so anything not named
    // here is dropped on the way in — which is silent, and looks exactly like a
    // shop's colour never having saved.
    brand_color: String(raw?.brand_color ?? '').trim().toLowerCase(),
    banner_image: String(raw?.banner_image ?? '').trim(),
    tagline: String(raw?.tagline ?? '').trim(),
    hero_headline: String(raw?.hero_headline ?? '').trim(),
    logo: String(raw?.logo ?? '').trim(),
  };
}

export function calcTaxAmount(subtotal: number, taxRatePct = 0): number {
  if (!subtotal || !taxRatePct) return 0;
  return Math.round(subtotal * taxRatePct / 100);
}

export function calcDeliveryFee(subtotal: number, settings: StorefrontSettings): number {
  if (subtotal <= 0) return 0;
  return subtotal >= settings.free_delivery_threshold ? 0 : settings.delivery_fee;
}

export function amountUntilFreeDelivery(subtotal: number, settings: StorefrontSettings): number {
  if (subtotal >= settings.free_delivery_threshold) return 0;
  return Math.max(0, settings.free_delivery_threshold - subtotal);
}

/** Public settings for a tenant storefront (no auth). */
export async function fetchPublicStoreSettings(tenantSlug: string): Promise<StorefrontSettings> {
  try {
    const r = await publicApi.get(`/storefront/${tenantSlug}/settings`);
    return normalizeStorefrontSettings(r.data.data);
  } catch {
    return { ...DEFAULT_STOREFRONT_SETTINGS };
  }
}

/** Merchant settings (authenticated). */
export async function fetchMerchantStoreSettings(): Promise<StorefrontSettings> {
  try {
    const r = await api.get('/storefront/settings');
    return normalizeStorefrontSettings(r.data.data);
  } catch {
    return { ...DEFAULT_STOREFRONT_SETTINGS };
  }
}

export async function saveMerchantStoreSettings(settings: StorefrontSettings): Promise<StorefrontSettings> {
  const r = await api.put('/storefront/settings', settings);
  return normalizeStorefrontSettings(r.data.data);
}

/** Public order lookup for customers. */
export async function trackStoreOrder(tenantSlug: string, reference: string) {
  const r = await publicApi.get(
    `/storefront/${tenantSlug}/orders/${encodeURIComponent(reference.trim())}`,
  );
  return r.data.data;
}
